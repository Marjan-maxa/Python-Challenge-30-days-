import pandas as pd
df=pd.read_csv("students.csv")
print("-------------------------------")
print("Student Information Report ")
print("-------------------------------")
print(df)
print("Total Students :",len(df)," Students")
print("Average CGPA :",round(df["cgpa"].mean(),2))
